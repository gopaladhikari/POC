# Operators

# Assignment Operators
a = 10
b = 20

# Arithmetic Operators
c = a + b
d = a - b
e = a * b
f = a / b
g = a % b
h = a**b
i = a // b  # floor division 10//3 = 3

print(c)
print(d)
print(e)
print(f)
print(g)
print(h)
print(i)

# Comparison Operators

print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)

# Logical Operators
x = True
y = False
z = x and y
w = x or y

print(z)
print(w)
